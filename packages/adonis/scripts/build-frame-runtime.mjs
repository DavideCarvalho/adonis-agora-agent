// Builds the JSX transpiler the sandbox frame runs into a self-contained string, committed as
// src/genui/sandbox-jsx-frame-generated.ts. The frame never gets library code through
// Function.prototype.toString: a consumer's minifier renames identifiers inside bundled functions
// (helpers like `__name`), and the stringified copy would then reference names that do not exist in
// the frame. A string literal survives any minifier as it is.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The transpiler as one self-contained script (defines `__genuiJsx`). */
export async function frameRuntimeCode() {
  const esbuild = await import('esbuild');
  const result = await esbuild.build({
    entryPoints: [fileURLToPath(new URL('../src/genui/sandbox-jsx.ts', import.meta.url))],
    bundle: true,
    format: 'iife',
    globalName: '__genuiJsx',
    minify: true,
    target: 'es2018',
    write: false,
    logLevel: 'silent',
  });
  // No "use strict" prologue: the frame wraps this source in a function of its own.
  return result.outputFiles[0].text.trim().replace(/^"use strict";/, '');
}

/** The generated module's text. */
export async function buildFrameRuntimeSource() {
  const code = await frameRuntimeCode();
  return `// GENERATED by scripts/build-frame-runtime.mjs from sandbox-jsx.ts — do not edit.\n// The sandbox frame's JSX transpiler, as a self-contained script defining \`__genuiJsx\`.\nexport const SANDBOX_JSX_FRAME_SOURCE: string = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    fileURLToPath(new URL('../src/genui/sandbox-jsx-frame-generated.ts', import.meta.url)),
    await buildFrameRuntimeSource(),
  );
}
